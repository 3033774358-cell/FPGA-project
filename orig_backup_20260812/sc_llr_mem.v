`timescale 1ns/1ps

// =============================================================================
// sc_llr_mem.v
// =============================================================================
// SC 译码器 LLR 存储模块
//
// 功能：
// 1. 串行装载根节点信道 LLR；
// 2. 保存 SC 译码过程中产生的中间层 LLR；
// 3. 提供两个组合读端口，供一个 PE 同时读取 a、b；
// 4. 提供一个时钟同步写端口，保存 PE 计算结果。
//
// -----------------------------------------------------------------------------
// 地址布局
// -----------------------------------------------------------------------------
//
// 存储器按照 SC 树的“深度 depth”进行分区。
//
// 每一个深度固定预留 NMAX 个地址：
//
//     depth_base = depth * NMAX
//
// 物理地址为：
//
//     address = depth * NMAX + layer_offset
//
// 对于当前码长 N = 2^n_log：
//
//     node_len    = N >> depth
//     layer_offset = node_id * node_len + element_index
//
// 因此：
//
//     address = depth * NMAX
//             + node_id * (N >> depth)
//             + element_index
//
// 其中：
//
//     depth         ：从根节点开始计数，根节点 depth=0
//     node_id        ：该深度下从左到右的节点编号
//     element_index  ：该节点内部的 LLR 编号
//
// -----------------------------------------------------------------------------
// N=4 地址示例，假设 NMAX=1024
// -----------------------------------------------------------------------------
//
// depth=0，根节点：
//
//     地址 0    ：根节点 d[0] 对应 LLR
//     地址 1    ：根节点 d[1] 对应 LLR
//     地址 2    ：根节点 d[2] 对应 LLR
//     地址 3    ：根节点 d[3] 对应 LLR
//
// depth=1，节点长度为2，基地址为1024：
//
//     地址 1024 ：左节点第0个 LLR
//     地址 1025 ：左节点第1个 LLR
//     地址 1026 ：右节点第0个 LLR
//     地址 1027 ：右节点第1个 LLR
//
// depth=2，叶节点层，基地址为2048：
//
//     地址 2048 ：u[0] 对应叶节点 LLR
//     地址 2049 ：u[1] 对应叶节点 LLR
//     地址 2050 ：u[2] 对应叶节点 LLR
//     地址 2051 ：u[3] 对应叶节点 LLR
//
// 对于 N=1024，共有 depth=0～10，共11层。
//
// -----------------------------------------------------------------------------
// 串行装载规则
// -----------------------------------------------------------------------------
//
// load_start 在空闲状态下拉高一个时钟周期，启动一次装载。
// 模块锁存：
//
//     N = 1 << n_log
//
// 当 llr_in_valid 与 llr_in_ready 同时为1时，接收一个 LLR：
//
//     第1个输入 → mem[0]，对应 d[0]
//     第2个输入 → mem[1]，对应 d[1]
//     ...
//     第N个输入 → mem[N-1]，对应 d[N-1]
//
// 不进行反序，也不进行 bit reversal。
//
// 接收第 N 个 LLR 后：
//
//     load_busy 拉低
//     load_done 拉高一个时钟周期
//
// -----------------------------------------------------------------------------
// 读写特性
// -----------------------------------------------------------------------------
//
// 读取：两个组合读端口
//
//     rd_data_a = mem[rd_addr_a]
//     rd_data_b = mem[rd_addr_b]
//
// 写入：时钟上升沿写入
//
//     wr_en=1 时：mem[wr_addr] <= wr_data
//
// 优先级：
//
//     根节点启动/装载 > 普通 wr_en 写入
//
// 当 load_busy=1 时，普通 wr_en 写入被忽略。
//
// -----------------------------------------------------------------------------
// 注意
// -----------------------------------------------------------------------------
//
// 1. 复位只清除控制状态，不清空整个 LLR 数组。
//    当前有效译码所需地址必须在使用前被写入。
//
// 2. 第一版使用组合双读寄存器数组。
//    后续替换同步 BRAM 时，读取会增加时钟延迟，C 控制模块需要相应调整。
//
// 3. 正常配置要求 INT_W >= LLR_W。
// =============================================================================

module sc_llr_mem #(
    parameter integer NMAX = 1024,
    parameter integer LLR_W = 8,
    parameter integer INT_W = 10,

    // NMAX=1024 时 MAX_LOG=10
    parameter integer MAX_LOG = $clog2(NMAX),


    parameter integer MEM_DEPTH = 2 * NMAX - 1,

    // NMAX=1024
    // MEM_DEPTH=2047
    // ADDR_W=11
    parameter integer ADDR_W = $clog2(MEM_DEPTH),

    // 需要能够表示 NMAX 本身：
    // NMAX=1024 时 N_W=11
    parameter integer N_W =  $clog2(NMAX)+1,

    // Fast-SSC: P 路宽读端口位宽
    parameter integer FAST_P = 8
)(
    input  wire                     clk,
    input  wire                     rst_n,

    // =========================================================================
    // 根节点串行装载接口
    // =========================================================================

    // 空闲状态下拉高一个周期，启动根节点 LLR 装载
    input  wire                     load_start,

    // 当前码长的 log2：
    // 6、7、8、9、10 分别对应 64～1024
    input  wire [3:0]               n_log,

    // 串行输入 LLR
    input  wire signed [LLR_W-1:0]  llr_in,

    // llr_in 当前周期有效
    input  wire                     llr_in_valid,

    // 模块能够接收 llr_in
    output wire                     llr_in_ready,

    // 正在装载根节点 LLR
    output reg                      load_busy,

    // 最后一个根节点 LLR 接收完成后，拉高一个周期
    output reg                      load_done,

    // =========================================================================
    // 普通同步写端口
    // =========================================================================

    // 普通写使能
    // 仅在 load_busy=0 时有效
    input  wire                     wr_en,

    // 写入物理地址
    input  wire [ADDR_W-1:0]        wr_addr,

    // 写入内部 LLR
    input  wire signed [INT_W-1:0]  wr_data,

    // =========================================================================
    // 双组合读端口
    // =========================================================================

    input  wire [ADDR_W-1:0]        rd_addr_a,
    output wire signed [INT_W-1:0]  rd_data_a,

    input  wire [ADDR_W-1:0]        rd_addr_b,
    output wire signed [INT_W-1:0]  rd_data_b,

    // =========================================================================
    // Fast-SSC 宽读接口（Rate-1 DECIDE 阶段一次读 P 个连续 LLR）
    // =========================================================================

    input  wire [ADDR_W-1:0]        rd_vec_addr,
    output wire [(FAST_P*INT_W)-1:0] rd_vec_data
);

    // =========================================================================
    // LLR 存储数组
    // =========================================================================

    reg signed [INT_W-1:0] llr_mem [0:MEM_DEPTH-1];

    // =========================================================================
    // 根节点装载状态
    // =========================================================================

    // 当前需要装载的 LLR 总数 N
    // NMAX=1024，因此必须使用11位表示1024
    reg [N_W-1:0] active_n;

    // 当前即将写入的根节点索引
    // 范围为 0～N-1
    reg [N_W-1:0] load_count;

    // =========================================================================
    // 输入 LLR 位宽转换
    // =========================================================================
    //
    // 默认：
    //
    //     LLR_W = 8
    //     INT_W = 10
    //
    // 例如：
    //
    //     8'b1110_0000 = -32
    //
    // 符号扩展后：
    //
    //     10'b11_1110_0000 = -32
    //
    // 不改变数值。
    // =========================================================================

    wire signed [INT_W-1:0] llr_in_ext;

    generate
    if(INT_W > LLR_W)
    begin

    assign llr_in_ext =
    {
     {(INT_W-LLR_W){llr_in[LLR_W-1]}},
     llr_in
    };
    end
    else
    begin
    assign llr_in_ext = llr_in;
    end
    endgenerate

    // =========================================================================
    // valid/ready 握手
    // =========================================================================

    assign llr_in_ready = load_busy;

    wire llr_in_fire;

    assign llr_in_fire = llr_in_valid && llr_in_ready;

    // =========================================================================
    // 双端口同步读取（注册输出）
    // =========================================================================
    //
    // PE_NUM=1，但一次 f/g 需要两个操作数，所以提供两个组合读地址。
    //
    // 2026-08-12：改为同步读（posedge 采样、寄存器输出）。
    // 异步组合读会让 Vivado 无法推断 BRAM，2047x10 阵列 + 10 个读口
    // 会展开成巨大的 address mux（综合卡死）。同步读可复制 BRAM，面积很小。
    //
    // 时序：地址在周期 T 生效，数据在上升沿 T+1 锁存输出（周期 T+1 有效）。
    // sc_datapath 现有 pipeline 已吸收这一拍延迟，译码结果不变。
    // =========================================================================

    reg signed [INT_W-1:0] rd_data_a_r;
    reg signed [INT_W-1:0] rd_data_b_r;

    always @(posedge clk) begin
        rd_data_a_r <= llr_mem[rd_addr_a];
        rd_data_b_r <= llr_mem[rd_addr_b];
    end

    assign rd_data_a = rd_data_a_r;
    assign rd_data_b = rd_data_b_r;

    // Fast-SSC 宽读：读取 rd_vec_addr 起始的 P 个连续条目
    //
    // 同样改为同步读。越界保护：rd_vec_addr + lane 先扩展到 ADDR_W+1 位再与 MEM_DEPTH 比较，
    // 避免 11 bit 加法回卷导致误判。lane 地址超出 MEM_DEPTH-1 时返回全 0，
    // 不允许访问 llr_mem 非法下标。
    reg signed [(FAST_P*INT_W)-1:0] rd_vec_data_r;

    generate
        genvar rvi2;
        for (rvi2 = 0; rvi2 < FAST_P; rvi2 = rvi2 + 1)
        begin : gen_rd_vec_reg
            wire [ADDR_W:0] rd_vec_lane_addr =
                {1'b0, rd_vec_addr} + rvi2;

            always @(posedge clk) begin
                if (rd_vec_lane_addr < MEM_DEPTH)
                    rd_vec_data_r[rvi2*INT_W +: INT_W] <=
                        llr_mem[rd_vec_lane_addr[ADDR_W-1:0]];
                else
                    rd_vec_data_r[rvi2*INT_W +: INT_W] <=
                        {INT_W{1'b0}};
            end
        end
    endgenerate

    assign rd_vec_data = rd_vec_data_r;

    // =========================================================================
    // 时序控制及写入
    // =========================================================================

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            load_busy  <= 1'b0;
            load_done  <= 1'b0;
            active_n   <= {N_W{1'b0}};
            load_count <= {N_W{1'b0}};
        end
        else begin
            // load_done 默认只保持一个周期
            load_done <= 1'b0;

            // =================================================================
            // 启动一次新的根节点装载
            // =================================================================
            //
            // 仅在当前空闲时接受 load_start。
            //
            // load_start 所在周期只启动装载，不接收第一个 LLR。
            // 下一个周期 llr_in_ready 才会变为1。
            // =================================================================

            if (load_start && !load_busy) begin
                active_n   <= (1 << n_log);
                load_count <= {N_W{1'b0}};
                load_busy  <= 1'b1;
            end

            // =================================================================
            // 根节点串行装载
            // =================================================================

            else if (load_busy) begin
                if (llr_in_fire) begin

                    // 根节点基地址固定为0
                    //
                    // load_count=0 → d[0]
                    // load_count=1 → d[1]
                    // ...
                    llr_mem[load_count] <= llr_in_ext;

                    // 当前是否为最后一个 LLR
                    if (load_count == (active_n - 1'b1)) begin
                        load_count <= {N_W{1'b0}};
                        load_busy  <= 1'b0;
                        load_done  <= 1'b1;
                    end
                    else begin
                        load_count <= load_count + 1'b1;
                    end
                end
            end

            // =================================================================
            // 普通写端口
            // =================================================================
            //
            // 只有不处于根节点装载状态时，wr_en 才有效。
            // =================================================================

            else if (wr_en) begin
                llr_mem[wr_addr] <= wr_data;
            end
        end
    end

endmodule
