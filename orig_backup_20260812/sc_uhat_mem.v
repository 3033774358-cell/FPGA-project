`timescale 1ns/1ps

// =============================================================================
// sc_uhat_mem.v
// =============================================================================
//
// SC 译码器最终判决位 u_hat 存储与串行输出模块
//
// =============================================================================
// 一、模块功能
// =============================================================================
//
// 1. 保存 SC 译码过程中得到的叶节点最终判决：
//
//        u_hat[phi]
//
//    写入索引 phi 使用自然顺序：
//
//        phi = 0      → u_hat[0]
//        phi = 1      → u_hat[1]
//        ...
//        phi = N-1    → u_hat[N-1]
//
// 2. 全部叶节点译码完成后，由外部控制模块拉高 output_start，
//    本模块开始按照自然顺序串行输出：
//
//        u_hat[0]、u_hat[1]、...、u_hat[N-1]
//
// 3. 串行输出采用 valid/ready 握手机制：
//
//        u_valid = 1：当前 u_bit、u_index、u_last 有效
//        u_ready = 1：下游能够接收当前输出
//
//    只有在：
//
//        u_valid && u_ready
//
//    同时为 1 时，输出索引才会推进。
//
// 4. 当 u_ready=0 时，本模块保持：
//
//        u_bit
//        u_index
//        u_last
//
//    不发生变化，直到该输出被下游接收。
//
// 5. 输出包含冻结位。
//
//    冻结位必须在写入本模块之前已经被强制判决为 0：
//
//        final_decision = leaf_frozen ? 1'b0 : leaf_llr_sign;
//
//    本模块只保存 wr_bit，不自行判断 frozen，也不读取叶节点 LLR。
//
// =============================================================================
// 二、不属于本模块的功能
// =============================================================================
//
// 本模块不负责：
//
// 1. SC 树深度优先遍历；
// 2. f/g 运算；
// 3. 冻结位判断；
// 4. 叶节点 LLR 正负判决；
// 5. beta 部分和更新；
// 6. 信息位抽取；
// 7. CRC 校验；
// 8. bit reversal。
//
// =============================================================================
// 三、写入规则
// =============================================================================
//
// 在 output_busy=0 时：
//
//        wr_en=1
//
// 会在时钟上升沿执行：
//
//        uhat_mem[wr_index] <= wr_bit;
//
// wr_index 与 u_hat 使用相同的自然索引。
//
// 在 output_busy=1 时，普通写入被忽略，以保证 valid/ready 反压期间
// 输出数据稳定。
//
// wr_en 和 output_start 可以在同一个空闲周期同时拉高。
// 这种情况下：
//
// 1. wr_bit 在该上升沿被写入；
// 2. 同时启动串行输出；
// 3. 第一个有效输出出现在该上升沿之后。
//
// 因此允许最后一个叶节点判决写入与 output_start 同周期出现。
// 不过正式控制模块仍建议将 output_start 放在最后一次写入之后一个周期，
// 以使控制时序更清晰。
//
// =============================================================================
// 四、输出规则
// =============================================================================
//
// output_start 仅在 output_busy=0 时有效。
//
// 启动时锁存：
//
//        active_n = 1 << n_log
//
// 支持：
//
//        n_log=6   → N=64
//        n_log=7   → N=128
//        n_log=8   → N=256
//        n_log=9   → N=512
//        n_log=10  → N=1024
//
// 输出接口：
//
//        u_valid：当前输出有效
//        u_ready：下游接收允许
//        u_bit  ：当前判决位
//        u_index：当前判决位自然索引
//        u_last ：当前判决位是 u_hat[N-1]
//
// 最后一个输出完成握手后：
//
//        output_busy 拉低
//        output_done 拉高一个时钟周期
//
// =============================================================================
// 五、复位原则
// =============================================================================
//
// 复位清除输出控制状态，并把 uhat_mem 全部清零，
// 保证 Fast-SSC 下未写（Rate-0/冻结）位置读出为 0 而不是 X。
//
// 原因：
//
// 1. 避免给 1024 个存储位增加不必要的复位逻辑；
// 2. 每次输出前，当前码块的有效 u_hat 地址应已全部写入；
// 3. 未写入地址的内容不应被使用。
//
// =============================================================================

module sc_uhat_mem #(
    parameter integer NMAX = 1024,

    // 固定配置 NMAX=1024 时，需要 11 位表示：
    // 0～1023 的索引以及 active_n=1024
    parameter integer INDEX_W = 11,

    // Fast-SSC: P 路宽读/写端口位宽
    parameter integer FAST_P = 8
)(
    input  wire                     clk,
    input  wire                     rst_n,

    // =========================================================================
    // u_hat 同步写接口
    // =========================================================================

    // 写使能
    input  wire                     wr_en,

    // 写入的自然索引 phi
    input  wire [INDEX_W-1:0]       wr_index,

    // 已完成冻结位处理和 LLR 符号判决的最终判决位
    input  wire                     wr_bit,

    // =========================================================================
    // 串行输出启动接口
    // =========================================================================

    // 空闲时拉高一个周期，启动 u_hat 串行输出
    input  wire                     output_start,

    // 当前码长的 log2
    // 合法取值为 6～10
    input  wire [3:0]               n_log,

    // 当前正在输出
    output reg                      output_busy,

    // 最后一个 u_hat 完成握手后拉高一个周期
    output reg                      output_done,

    // =========================================================================
    // valid/ready 串行输出接口
    // =========================================================================

    // 当前输出有效
    output wire                     u_valid,

    // 下游准备接收当前输出
    input  wire                     u_ready,

    // 当前输出判决位
    output wire                     u_bit,

    // 当前输出自然索引
    output wire [10:0]              u_index,

    // 当前输出是否为 u_hat[N-1]
    output wire                     u_last,

    // =========================================================================
    // Fast-SSC 宽读/宽写接口
    // =========================================================================
    //
    // frozen_bits：输出阶段把冻结位强制判 0，
    //               因此 Rate-0 子树无需写 u_hat。
    // 宽写：Rate-1 DECIDE / TRANSFORM 阶段按 P 位写入。
    // 宽读：TRANSFORM 阶段一次读两段各 P 位做原位变换。
    // =========================================================================

    input  wire [NMAX-1:0]          frozen_bits,

    input  wire [FAST_P-1:0]        wr_vec_en,
    input  wire [INDEX_W-1:0]       wr_vec_index,
    input  wire [FAST_P-1:0]        wr_vec_bits,

    input  wire [INDEX_W-1:0]       rd_vec_addr_a,
    output wire [FAST_P-1:0]        rd_vec_data_a,

    input  wire [INDEX_W-1:0]       rd_vec_addr_b,
    output wire [FAST_P-1:0]        rd_vec_data_b
);

    // =========================================================================
    // u_hat 存储数组
    // =========================================================================
    //
    // 自然顺序存储：
    //
    //     uhat_mem[0]     = u_hat[0]
    //     uhat_mem[1]     = u_hat[1]
    //     ...
    //     uhat_mem[N-1]   = u_hat[N-1]
    //
    // 第一版使用寄存器数组。
    // =========================================================================

    reg uhat_mem [0:NMAX-1];

    integer wi;
    integer ri;

    // =========================================================================
    // 输出控制寄存器
    // =========================================================================

    // 当前码长 N
    //
    // 需要表示 NMAX=1024，因此使用 11 位。
    reg [INDEX_W-1:0] active_n;

    // 当前正在输出的 u_hat 索引
    reg [INDEX_W-1:0] output_index;

    // =========================================================================
    // valid/ready 握手
    // =========================================================================

    wire u_fire;

    assign u_valid = output_busy;

    assign u_fire = u_valid && u_ready;

    // =========================================================================
    // 输出数据
    // =========================================================================
    //
    // output_index 在反压期间保持不变，并且 output_busy 期间禁止写存储器，
    // 因此 u_bit、u_index 和 u_last 均能够保持稳定。
    // =========================================================================

    // Fast-SSC: 冻结位输出强制为 0
    assign u_bit =
        frozen_bits[output_index]
        ? 1'b0
        : uhat_mem[output_index];

    // 固定输出接口要求 u_index 为 11 位。
    assign u_index = output_index[10:0];

    assign u_last =
        output_busy &&
        (output_index == (active_n - 1'b1));

    // =========================================================================
    // Fast-SSC 宽同步读
    // =========================================================================
    //
    // 2026-08-12：由组合读改为同步读，避免在 1024 深度阵列上展开
    // 16 个异步 address mux。串行输出读仍为组合（1 bit 1024:1 mux 很便宜）。
    //

    reg [FAST_P-1:0] rd_vec_data_a_r;
    reg [FAST_P-1:0] rd_vec_data_b_r;

    generate
        genvar rvi2;
        for (rvi2 = 0; rvi2 < FAST_P; rvi2 = rvi2 + 1)
        begin : gen_rd_vec_reg
            always @(posedge clk) begin
                if (rd_vec_addr_a + rvi2 < NMAX)
                    rd_vec_data_a_r[rvi2] <= uhat_mem[rd_vec_addr_a + rvi2];
                else
                    rd_vec_data_a_r[rvi2] <= 1'b0;

                if (rd_vec_addr_b + rvi2 < NMAX)
                    rd_vec_data_b_r[rvi2] <= uhat_mem[rd_vec_addr_b + rvi2];
                else
                    rd_vec_data_b_r[rvi2] <= 1'b0;
            end
        end
    endgenerate

    assign rd_vec_data_a = rd_vec_data_a_r;
    assign rd_vec_data_b = rd_vec_data_b_r;

    // =========================================================================
    // 写入及串行输出控制
    // =========================================================================

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // 复位把 uhat_mem 全部清零：
            // Fast-SSC 下 Rate-0/冻结子树不写 u_hat，
            // 未写地址必须读出 0 而不是 X
            // （输出阶段 frozen 掩码仍保留，这里是双保险）。
            for (ri = 0; ri < NMAX; ri = ri + 1) begin
                uhat_mem[ri] <= 1'b0;
            end

            output_busy  <= 1'b0;
            output_done  <= 1'b0;
            active_n     <= {INDEX_W{1'b0}};
            output_index <= {INDEX_W{1'b0}};
        end
        else begin

            // output_done 默认只维持一个时钟周期
            output_done <= 1'b0;

            // =================================================================
            // 空闲状态
            // =================================================================

            if (!output_busy) begin

                // -------------------------------------------------------------
                // u_hat 写入
                // -------------------------------------------------------------
                //
                // 只在输出空闲时允许写入。
                //
                // output_start 与 wr_en 同周期出现时，两项操作均会执行。
                // -------------------------------------------------------------

                if (wr_en) begin
                    uhat_mem[wr_index] <= wr_bit;
                end

                // -------------------------------------------------------------
                // Fast-SSC 宽写（仅输出空闲时允许）
                // -------------------------------------------------------------

                if (|wr_vec_en) begin
                    for (wi = 0; wi < FAST_P; wi = wi + 1) begin
                        if (wr_vec_en[wi]) begin
                            uhat_mem[wr_vec_index + wi] <= wr_vec_bits[wi];
                        end
                    end
                end

                // -------------------------------------------------------------
                // 启动串行输出
                // -------------------------------------------------------------

                if (output_start) begin
                    active_n     <= (11'd1 << n_log);
                    output_index <= {INDEX_W{1'b0}};
                    output_busy  <= 1'b1;
                end
            end

            // =================================================================
            // 串行输出状态
            // =================================================================

            else begin

                // 只有 valid 和 ready 同时有效时才推进输出索引
                if (u_fire) begin

                    // 当前是最后一个输出
                    if (output_index == (active_n - 1'b1)) begin
                        output_busy  <= 1'b0;
                        output_done  <= 1'b1;
                        output_index <= {INDEX_W{1'b0}};
                    end
                    else begin
                        output_index <= output_index + 1'b1;
                    end
                end
            end
        end
    end

endmodule
