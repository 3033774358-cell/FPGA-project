`timescale 1ns/1ps


// =============================================================================
// sc_beta_mem.v
// =============================================================================
//
// SC译码器部分和(beta)存储模块
//
// 功能:
// -----------------------------------------------------------------------------
// 1. 保存SC译码过程中产生的部分和(partial sum)
//
// 2. 保存叶节点判决结果对应的beta:
//
//        beta(phi)=u_hat(phi)
//
// 3. 保存内部节点经过子节点合并后的partial sum
//
// 4. 提供两个组合读端口:
//        用于父节点beta更新时同时读取两个子beta
//
// 5. 提供一个同步写端口:
//        由C控制模块指定地址写入beta
//
//
// 不负责:
// -----------------------------------------------------------------------------
// × SC树遍历
// × beta递推算法
// × f/g计算
// × 叶节点判决
// × frozen判断
//
//
// 地址布局:
// -----------------------------------------------------------------------------
//
// 与sc_llr_mem保持一致
//
// 使用DFS工作区:
//
// depth0:
//     0 ~ NMAX-1
//
// depth1:
//     NMAX ~ NMAX+NMAX/2-1
//
// ...
//
// depth10:
//     2046
//
// 总空间:
//
//     MEM_DEPTH = 2*NMAX-1
//
//
// NMAX=1024:
//
//     MEM_DEPTH=2047
//
// =============================================================================


module sc_beta_mem #(

    parameter integer NMAX = 1024,

    parameter integer MEM_DEPTH = 2*NMAX-1,

    parameter integer ADDR_W = $clog2(MEM_DEPTH)

)(

    input  wire                 clk,

    input  wire                 rst_n,


    // =========================================================================
    // 同步写接口
    // =========================================================================

    input  wire                 wr_en,

    input  wire [ADDR_W-1:0]    wr_addr,

    input  wire                 wr_data,


    // =========================================================================
    // 双组合读接口
    // =========================================================================

    input  wire [ADDR_W-1:0]    rd_addr_a,

    output wire                 rd_data_a,


    input  wire [ADDR_W-1:0]    rd_addr_b,

    output wire                 rd_data_b


);



////////////////////////////////////////////////////////////
// beta存储阵列
////////////////////////////////////////////////////////////


(* ram_style = "block" *)               // 显式请求 Vivado 用块 RAM(BRAM)
reg beta_mem [0:MEM_DEPTH-1];



////////////////////////////////////////////////////////////
// 组合读
////////////////////////////////////////////////////////////


// 同步读(寄存一拍)-> 可推断成块 RAM; 控制器 rd_ph 已配 1 拍读延迟
reg rd_data_a_r, rd_data_b_r;
always @(posedge clk) rd_data_a_r <= beta_mem[rd_addr_a];
always @(posedge clk) rd_data_b_r <= beta_mem[rd_addr_b];
assign rd_data_a = rd_data_a_r;
assign rd_data_b = rd_data_b_r;



////////////////////////////////////////////////////////////
// 同步写
////////////////////////////////////////////////////////////
//
// 复位不清空beta_mem
//
// 因为:
// 1. 未写入地址不会被使用
// 2. 避免大量寄存器复位资源
//
////////////////////////////////////////////////////////////


// 写口: 无复位独立块 -> Vivado 推断块 RAM/BRAM (复位不清空存储, 用前必写)
always @(posedge clk)
begin
    if(wr_en)
    begin
        beta_mem[wr_addr] <= wr_data;
    end
end



endmodule