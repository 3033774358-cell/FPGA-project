`timescale 1ns/1ps

// =============================================================================
// sc_pe.v
// -----------------------------------------------------------------------------
// SC 译码器 Processing Element
//
// mode_g = 0：执行 min-sum f 运算
// mode_g = 1：执行 g 运算
//
// f(a,b) = sign(a) * sign(b) * min(|a|, |b|)
//
// g(a,b,beta) = beta ? (b-a) : (b+a)
//
// 输入、输出均为 W 位有符号数。
// 所有结果均饱和到：
//     MIN = -2^(W-1)
//     MAX =  2^(W-1)-1
//
// 本模块为纯组合逻辑。
// =============================================================================

module sc_pe #(
    parameter integer W = 10
)(
    input  wire signed [W-1:0] a,
    input  wire signed [W-1:0] b,
    input  wire                mode_g,
    input  wire                beta,
    output reg  signed [W-1:0] y
);

    // -------------------------------------------------------------------------
    // W+1 位有符号饱和边界
    //
    // 以 W=10 为例：
    // MAX_EXT = +511
    // MIN_EXT = -512
    // -------------------------------------------------------------------------
    localparam signed [W:0] MAX_EXT =
        {2'b00, {(W-1){1'b1}}};

    localparam signed [W:0] MIN_EXT =
        {2'b11, {(W-1){1'b0}}};

    // -------------------------------------------------------------------------
    // 绝对值的无符号边界
    //
    // MAX_MAG = 2^(W-1)-1
    // MIN_MAG = 2^(W-1)
    //
    // MIN_MAG 对应最小负数的绝对值。
    // 例如 W=10 时，|-512|=512。
    // -------------------------------------------------------------------------
    localparam [W:0] MAX_MAG =
        {2'b00, {(W-1){1'b1}}};

    localparam [W:0] MIN_MAG =
        {2'b01, {(W-1){1'b0}}};

    // W 位输出边界
    localparam signed [W-1:0] MAX_OUT =
        {1'b0, {(W-1){1'b1}}};

    localparam signed [W-1:0] MIN_OUT =
        {1'b1, {(W-1){1'b0}}};

    // f 运算中使用 W+1 位无符号绝对值
    reg [W:0] abs_a;
    reg [W:0] abs_b;
    reg [W:0] min_abs;

    reg f_negative;

    // g 运算中使用 W+1 位有符号数
    reg signed [W:0] a_ext;
    reg signed [W:0] b_ext;
    reg signed [W:0] g_ext;

    always @* begin
        // 默认赋值，避免组合锁存
        y          = {W{1'b0}};

        abs_a      = {(W+1){1'b0}};
        abs_b      = {(W+1){1'b0}};
        min_abs    = {(W+1){1'b0}};
        f_negative = 1'b0;

        // 明确进行符号扩展
        a_ext      = {a[W-1], a};
        b_ext      = {b[W-1], b};
        g_ext      = {(W+1){1'b0}};

        // =====================================================================
        // f 运算
        // =====================================================================
        if (!mode_g) begin

            // -----------------------------------------------------------------
            // 求 |a|
            //
            // 必须先扩展为 W+1 位，再执行二进制补码取负。
            // 这样才能正确处理最小负数。
            // -----------------------------------------------------------------
            if (a[W-1]) begin
                abs_a =
                    (~{a[W-1], a})
                    + {{W{1'b0}}, 1'b1};
            end
            else begin
                abs_a = {1'b0, a};
            end

            // 求 |b|
            if (b[W-1]) begin
                abs_b =
                    (~{b[W-1], b})
                    + {{W{1'b0}}, 1'b1};
            end
            else begin
                abs_b = {1'b0, b};
            end

            // 取较小绝对值
            if (abs_a < abs_b)
                min_abs = abs_a;
            else
                min_abs = abs_b;

            // 两输入异号时，f 结果为负
            f_negative = a[W-1] ^ b[W-1];

            if (f_negative) begin
                // -------------------------------------------------------------
                // 负结果
                //
                // -2^(W-1) 可以由 W 位表示。
                // 若绝对值达到或超过 MIN_MAG，则饱和到 MIN_OUT。
                // -------------------------------------------------------------
                if (min_abs >= MIN_MAG) begin
                    y = MIN_OUT;
                end
                else begin
                    // 对 min_abs 的低 W 位执行二进制补码取负
                    y =
                        (~min_abs[W-1:0])
                        + {{(W-1){1'b0}}, 1'b1};
                end
            end
            else begin
                // -------------------------------------------------------------
                // 正结果
                //
                // +2^(W-1) 无法由 W 位有符号数表示。
                // 例如 f(-512,-512)=+512，需要饱和到 +511。
                // -------------------------------------------------------------
                if (min_abs > MAX_MAG)
                    y = MAX_OUT;
                else
                    y = $signed(min_abs[W-1:0]);
            end
        end

        // =====================================================================
        // g 运算
        // =====================================================================
        else begin
            if (beta)
                g_ext = b_ext - a_ext;
            else
                g_ext = b_ext + a_ext;

            // 明确执行有符号饱和比较
            if (g_ext > MAX_EXT)
                y = MAX_OUT;
            else if (g_ext < MIN_EXT)
                y = MIN_OUT;
            else
                y = g_ext[W-1:0];
        end
    end

endmodule